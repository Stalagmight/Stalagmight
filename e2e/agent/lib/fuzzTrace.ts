/**
 * One replayable move.
 *
 * `save` is the whole boundary crossing (save to a temp path, close, reopen), not
 * just the write: the three are one atomic thing as far as the model is
 * concerned, and splitting them would let a shrink produce a trace that saved
 * without reopening.
 */
export type TraceStep =
  | { kind: 'mutate'; action: string; args: unknown[]; label: string }
  // One literal `kind` per member, not `'undo' | 'redo'` on a shared one: the
  // replayer narrows on it, and TypeScript will not discharge a member whose
  // discriminant is itself a union.
  | { kind: 'undo' }
  | { kind: 'redo' }
  | { kind: 'undoTo'; steps: number }
  | { kind: 'redoTo'; steps: number }
  | { kind: 'save' }
  | { kind: 'repair' }
  // ---- v2: the import/export vocabulary -----------------------------------
  /** A click on a `data-testid`. The label is what a human reads in a shrink. */
  | { kind: 'ui'; testid: string; double?: boolean; label: string }
  /** Text typed, an option selected, or a checkbox set on a `data-testid`. */
  | { kind: 'input'; testid: string; value: string; mode: 'type' | 'select' | 'check'; label: string }
  /**
   * A control that opens a native file dialog, and the answer given to it.
   * `rel` is null for a cancel, one path for a save or single open, a list for a
   * multi-select.
   */
  | { kind: 'fileDialog'; trigger: string; dialog: 'open' | 'save'; rel: string | string[] | null; label: string }
  /**
   * An input file built from a `surveyFileSpecs` spec and written at `rel`.
   * The SPEC travels, not the bytes: `surveyFileWriters.ts` is a pure function
   * of it, so the replayer rebuilds the identical file without the trace
   * carrying a fixture (which the repo forbids) or a megabyte of base64.
   */
  /**
   * The start of one EPISODE, and whether it ran with no project open.
   *
   * A replay used to be one pass over the whole step list, so every step
   * belonged to episode 0 whatever it was recorded under - a later episode's
   * headless choice could never apply to its own steps. These markers are what
   * let a replay rebuild the recording's episode structure instead of guessing
   * it. Same precedent as `reload`: a step that carries control flow rather than
   * a move.
   */
  | { kind: 'episode'; index: number; headless: boolean; label: string }
  /**
   * The start of one FLOW inside the current episode.
   *
   * F3 compares a receipt against the delta of ITS OWN flow. Without these a
   * replay has no flow boundaries at all - a recording that imported three
   * times replayed as one flow - and the comparison is between things that are
   * not each other's pair.
   */
  | { kind: 'flow'; index: number; label: string }
  | { kind: 'genFile'; spec: unknown; rel: string; label: string }
  /**
   * An input file taken from the replayer's OWN private corpus and copied to
   * `rel`.
   *
   * `corpusId` is the entry's PUBLISHABLE ID - `fixtureCorpus.corpusFileId`, a
   * 5-hex fold of its corpus-relative path - and never the path itself. It is
   * what `describeStep` prints and what the metric keys beside it carry.
   *
   * `corpusHash` (v4, optional) is `fixtureCorpus.corpusPathHash` over the same
   * relative path: 16 hex of SHA-256, a LOOKUP KEY that is never rendered. It is
   * here because 20 bits does not resolve - a corpus of a few thousand files
   * probably holds a colliding pair, and taking the first match would materialize
   * the wrong private file and then open it under the recorded file's name. The
   * replayer prefers it and falls back to nothing rather than to a guess.
   *
   * Either way the trace carries no name, no root and no content, and a replayer
   * whose corpus holds no such file skips the step and counts it.
   *
   * The fields are NAMED for what they hold. `corpusId` was `corpusRel` in v2,
   * when it held the path, and a `...Rel` field quietly holding a crc id is
   * exactly how the next reader talks themselves into putting a path back in it.
   */
  | { kind: 'corpusFile'; corpusId: string; corpusHash?: string; rel: string; label: string }
  /**
   * An ORACLE the scenario ran, and the inputs it DREW to run it.
   *
   * A structural oracle is not a move, so it was not a step, so a replay could
   * only re-ASK it - and re-asking drew fresh options off an rng the replay had
   * consumed differently, which meant an option-dependent failure could be
   * retested with options that do not provoke it. `inputs` is the resolved draw
   * (`{}` for an oracle that draws nothing), so a replay runs the oracle the
   * recording ran, in the order and at the multiplicity the recording ran it.
   *
   * `oracle` names one of a scenario's OWN oracles; the scenario refuses a name
   * it does not have, exactly as it refuses a `mutate` action outside its
   * replayable set.
   */
  | { kind: 'oracle'; oracle: string; inputs: unknown; label: string }
  /** A file handed to the app by path rather than through a dialog. */
  | { kind: 'route'; rel: string; label: string }
  | { kind: 'mapClick'; lngLat: [number, number]; label: string }
  | { kind: 'export'; format: string; options: unknown; rel: string; label: string }
  /** Reopen the named tracked fixture, discarding the current project. */
  | { kind: 'reload'; fixture: string };

/**
 * `mutate` actions whose `args[0]` is an INPUT FILE PATH, not a value.
 *
 * The undo-redo-fuzz v3 import group drives the store's file importers, and a
 * store action that takes a path is the one shape a `mutate` step cannot carry
 * verbatim: the recording machine's absolute path means nothing on a replayer,
 * and a trace is meant to be attachable to a bug report. So those steps record a
 * SESSION-RELATIVE path (paired with a `genFile` step carrying the spec to
 * rebuild the file from), and the replayer resolves it against its own files
 * directory - keyed on exactly this set, because a trace has no other way to say
 * "argument zero is a path".
 *
 * It is a security boundary as much as a portability one, and the same one every
 * v2 `rel` field has: without the check below, a hand-written trace could name
 * `/etc/shadow` (or `../../../.ssh/id_rsa`) as the file for `executeTmlImport`
 * and have the app open and parse it. `validateStep` refuses that outright, so
 * the only thing a trace can point the importers at is a path inside the session
 * directory the replayer chose.
 *
 * Kept HERE rather than beside the generators because this file is the one that
 * reads untrusted input; `undoRedoFuzz.ts` imports it for resolution and
 * `undoRedoFuzzImportActions.test.ts` pins that every file-bearing generator
 * names one of these.
 */
export const FILE_ARG_ACTIONS: ReadonlySet<string> = new Set([
  'importDmp',
  'executeTmlImport',
  'executeCompassImport',
  'executeWallsImport',
  'executeGpxImport',
  'calculateFileHash',
]);

/** A failure, reduced to the parts that identify it across a shrink. */
export interface FailureSignature {
  /** First line of the failure, with every run of digits replaced by `N`. */
  headline: string;
  /** First differing path, with array indices normalized (`shots[3]` -> `shots[*]`). */
  path: string | null;
  /** The `error:` line of a move that failed outright, digits normalized. */
  error: string | null;
  /** Every classifier id the message named, sorted and deduped. */
  classifiers: string[];
}

export interface FuzzTrace {
  v: number;
  scenario: string;
  /** The seed that produced it. Replay does not need it; triage does. */
  seed: number;
  iterations: number;
  fixture: string;
  /** Generator stream the recording ran on (`v1` / `v2`), for the header only. */
  stream: string;
  /** The `STALAGMIGHT_FUZZ_*` / `STALAGMIGHT_PERSIST_FUZZ_*` knobs that were set. */
  env: Record<string, string>;
  gitRev: string;
  recordedAt: string;
  /** Null when the run passed and the trace was written because of the env var. */
  failure: { message: string; signature: FailureSignature } | null;
  /**
   * Episode indices the recording ran with NO PROJECT OPEN, in order.
   *
   * A per-episode coin toss, and one that changes which import flow the SAME
   * file steps drive: with nothing loaded a `.dmp` routes through
   * `new-project-for-import`, and with the fixture open it goes straight to the
   * selection dialog. Restoring `STALAGMIGHT_FUZZ_IMPORT_NO_PROJECT_P` is not
   * enough - it restores the ODDS, and a replay does not re-draw them.
   *
   * OPTIONAL, and absent means "assume the fixture stayed open", which is what
   * every replay did before this field existed. Refusing such a trace was the
   * alternative and it is the wrong trade: it would invalidate every trace
   * already kept for shrinking, to fix a gap that only bites a recording whose
   * episodes actually went headless. The scenario warns instead, and only when
   * the restored odds say the recording COULD have had one.
   */
  noProjectEpisodes?: number[];
  steps: TraceStep[];
}

/** One replayed episode: its no-project state and its flows, each a step list. */
export interface ReplayEpisode {
  headless: boolean;
  flows: TraceStep[][];
}

/**
 * Rebuild a recording's EPISODE and FLOW structure from its boundary steps.
 *
 * A replay used to be one pass over the whole step list against a single global
 * cursor, so episode 0 drained everything and every later episode replayed
 * nothing. Two things broke on that: a later episode's headless choice could
 * never reach the steps recorded under it, and F3 had no flow boundaries, so it
 * compared one receipt's claim against the delta of every import in the trace.
 *
 * A trace WITHOUT markers - anything recorded before they existed - folds into a
 * single episode holding every step, which is exactly what the old replay did,
 * so those traces keep replaying the way they always have. Its headless state
 * comes from the header's `noProjectEpisodes` when it has one.
 */
export function planReplay(trace: Pick<FuzzTrace, 'steps' | 'noProjectEpisodes'>): ReplayEpisode[] {
  const headlessHeader = new Set(trace.noProjectEpisodes ?? []);
  const episodes: ReplayEpisode[] = [];
  for (const step of trace.steps) {
    if (step.kind === 'episode') {
      episodes.push({ headless: step.headless, flows: [[]] });
      continue;
    }
    if (episodes.length === 0) {
      episodes.push({ headless: headlessHeader.has(0), flows: [[]] });
    }
    const current = episodes[episodes.length - 1] as ReplayEpisode;
    if (step.kind === 'flow') {
      current.flows.push([]);
      continue;
    }
    (current.flows[current.flows.length - 1] as TraceStep[]).push(step);
  }
  for (const episode of episodes) {
    // A marker at the very end of an episode would otherwise replay as an empty
    // flow and be measured as one.
    episode.flows = episode.flows.filter((flow) => flow.length > 0);
    if (episode.flows.length === 0) episode.flows = [[]];
  }
  return episodes;
}

/**
 * Are this trace's flow boundaries WELL FORMED - every step inside a marked flow?
 *
 * "Some step is a flow marker" was the old test and it is not strong enough,
 * because a shrink hands this function step lists nobody recorded. ddmin tries
 * arbitrary subsequences, so a candidate could delete the marker that opened the
 * FAILING flow while keeping a later one: any-marker-present still said yes, F3
 * stayed armed, and `planReplay` folded the now-unmarked steps into whatever
 * flow preceded them. F3's failure headline normalizes every run of digits, so a
 * merged-delta accounting failure carries the SAME signature as the recorded one
 * - which is exactly the check that is supposed to stop a shrink wandering, and
 * it cannot see this. ddmin would then accept a minimized trace that fails on a
 * boundary the recording never had.
 *
 * `shrinkableSteps` is the other half and the primary fix: markers travel with
 * their segment, so a shrink cannot produce this shape at all. This is the
 * defense in depth, for the step lists that do not come from there - a
 * hand-edited trace, an older tool, a file somebody mailed.
 *
 * A trace with no markers at all is unbounded, not partially bounded, and
 * returns false the same way it always did: F3 disarms and every other oracle
 * runs.
 */
export function traceHasWellFormedFlows(trace: Pick<FuzzTrace, 'steps'>): boolean {
  let insideMarkedFlow = false;
  let sawFlowMarker = false;
  for (const step of trace.steps) {
    if (step.kind === 'episode') {
      // An episode opens no flow of its own: its first flow needs its own
      // marker, which is what the recorder writes.
      insideMarkedFlow = false;
      continue;
    }
    if (step.kind === 'flow') {
      insideMarkedFlow = true;
      sawFlowMarker = true;
      continue;
    }
    if (!insideMarkedFlow) return false;
  }
  return sawFlowMarker;
}

/**
 * A trace split into the steps a shrink may DELETE and the structure it may not.
 *
 * `episode` and `flow` steps are not moves; they are the grouping the replay is
 * rebuilt from, and the oracles measure per group. Handing them to ddmin as
 * ordinary elements let it delete a boundary and merge two flows into one - a
 * trace shape the recorder cannot produce, measuring a delta no run ever had.
 *
 * So ddmin runs over `payload` (the real moves) and `rebuild` puts the structure
 * back: each marker survives exactly when something it scopes survived. The
 * grouping of the steps that remain is therefore always the recorded grouping,
 * restricted to survivors. It is also a strictly smaller search space, so this
 * costs nothing in replays.
 *
 * TWO asymmetries, both deliberate:
 *
 * - An empty `flow` marker is DROPPED, because `planReplay` already filters
 *   empty flows; keeping it would change nothing and read as a flow that ran.
 * - A HEADLESS `episode` marker is kept even with nothing left inside it. It is
 *   not just a label: the replay closes the project on it, and that outlives the
 *   episode. A non-headless empty episode does nothing and is dropped.
 */
export interface ShrinkableSteps {
  /** Indices into the original list, one per non-marker step, in order. */
  payload: number[];
  /** A well-formed step list from any subset of `payload`. */
  rebuild(kept: readonly number[]): TraceStep[];
}

export function shrinkableSteps(steps: readonly TraceStep[]): ShrinkableSteps {
  const payload: number[] = [];
  const flowMarkerOf = new Map<number, number>();
  const episodeMarkerOf = new Map<number, number>();
  const alwaysKeep = new Set<number>();
  let openFlow = -1;
  let openEpisode = -1;
  steps.forEach((step, index) => {
    if (step.kind === 'episode') {
      openEpisode = index;
      openFlow = -1;
      if (step.headless) alwaysKeep.add(index);
      return;
    }
    if (step.kind === 'flow') {
      openFlow = index;
      return;
    }
    payload.push(index);
    if (openFlow >= 0) flowMarkerOf.set(index, openFlow);
    if (openEpisode >= 0) episodeMarkerOf.set(index, openEpisode);
  });

  const rebuild = (kept: readonly number[]): TraceStep[] => {
    const keep = new Set(kept);
    const markers = new Set(alwaysKeep);
    for (const index of keep) {
      const flow = flowMarkerOf.get(index);
      if (flow !== undefined) markers.add(flow);
      const episode = episodeMarkerOf.get(index);
      if (episode !== undefined) markers.add(episode);
    }
    return steps.filter((step, index) =>
      step.kind === 'episode' || step.kind === 'flow' ? markers.has(index) : keep.has(index),
    );
  };

  return { payload, rebuild };
}

/**
 * Env knobs that change what a run does, and so belong in a trace header.
 *
 * These prefixes define a CLOSED SET, and that is load-bearing on the restoring
 * side: within them, a trace's `env` is the complete truth, and a key it does
 * not carry is one the recording did not have. So a knob must be named with one
 * of these prefixes to be honoured on replay - and adding a knob outside them
 * makes it invisible to record/replay, which is a silent divergence rather than
 * a missing feature. See `restoreTraceEnv` for the other half.
 */
const RECORDED_ENV_PREFIXES = ['STALAGMIGHT_FUZZ_', 'STALAGMIGHT_PERSIST_FUZZ_'];

/**
 * Knobs that match the prefixes above and are STILL never carried or restored.
 *
 * Each names an output or input PATH rather than what the run does, and each is
 * set by the caller that is about to run - so honouring a file's opinion about
 * them lets that file decide where this process writes (`_TRACE`), what it
 * replays next (`_REPLAY`), or which directory tree it walks and copies out of
 * (`_CORPUS_DIR`). The exclusion has to hold on BOTH sides, or it is a
 * convention rather than a boundary.
 *
 * `_CORPUS_DIR` is also the header's half of the v3 privacy rule. It is an
 * absolute path on the RECORDER's disk, and one whose own segments can name a
 * cave system or a landowner, so carrying it would put back in the header
 * exactly what the `corpusFile` step stopped putting in the steps - and
 * `scenario-run.ts` prints every restored knob as `KEY=value`. A replay resolves
 * corpus ids against the corpus the REPLAYER configured, which is the only one
 * it can read anyway.
 */
const NEVER_RESTORED = [
  'STALAGMIGHT_FUZZ_TRACE',
  'STALAGMIGHT_FUZZ_REPLAY',
  'STALAGMIGHT_FUZZ_CORPUS_DIR',
];

/**
 * Restore a trace's recorded environment - filtered to the SAME prefixes the
 * recorder writes.
 *
 * The filter has to exist on BOTH sides. `recordedEnv` applying it is a
 * producer-side convention; a trace is a file, and a file arrives from wherever
 * the reader got it - the docs tell people to attach one to a bug report and
 * shrink it. Restoring its keys verbatim would let that file set `PATH`,
 * `NODE_OPTIONS`, `LD_PRELOAD` or `RUSTFLAGS` for a run that then invokes cargo,
 * launches the app, and (in `fuzz-matrix`) spreads the whole environment into
 * every child process.
 *
 * Returns what it applied and what it refused, so the caller can print both:
 * a silently dropped knob would be a replay that quietly is not the recording.
 */
export function restoreTraceEnv(recorded: Readonly<Record<string, string>>): {
  applied: [string, string][];
  refused: string[];
  cleared: string[];
} {
  const applied: [string, string][] = [];
  const refused: string[] = [];
  for (const [key, value] of Object.entries(recorded)) {
    if (NEVER_RESTORED.includes(key)) {
      refused.push(key);
      continue;
    }
    if (RECORDED_ENV_PREFIXES.some((prefix) => key.startsWith(prefix))) {
      process.env[key] = value;
      applied.push([key, value]);
    } else {
      refused.push(key);
    }
  }
  // The recorded env is the WHOLE truth about restorable knobs, so a knob the
  // recording did not have is unset here rather than inherited.
  //
  // Only SET keys are recorded, so a run on a knob's DEFAULT writes no entry for
  // it - and restoring "every key the trace has" then leaves a shell override in
  // place. That is a divergence with no signal anywhere: a trace recorded with
  // the default replays against the override and silently is not the recording.
  // The instance that surfaced it is `STALAGMIGHT_FUZZ_IMPORT_FORCE_STATIONS`
  // (default on; a replay shell with `0` skips `ensureStationsVisible` and the
  // walk falls into the cancel loop), but it is a property of the mechanism, not
  // of that knob: EVERY knob whose default differs from a shell value has it.
  //
  // Clearing here fixes the whole class in one place and needs no list of knobs
  // or defaults - unset restores the default by construction, which is what the
  // recording ran on. `NEVER_RESTORED` is exempt in both directions: those name
  // an output or input PATH the CALLER owns (where to write a trace, what to
  // replay next, which corpus tree to walk), so a file must neither set them nor
  // take them away.
  const cleared: string[] = [];
  for (const key of Object.keys(process.env)) {
    if (key in recorded || NEVER_RESTORED.includes(key)) continue;
    if (!RECORDED_ENV_PREFIXES.some((prefix) => key.startsWith(prefix))) continue;
    delete process.env[key];
    cleared.push(key);
  }
  return { applied, refused, cleared };
}

function recordedEnv(): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [key, value] of Object.entries(process.env)) {
    if (value === undefined) continue;
    // The trace's own path is not part of what the run DOES, and carrying it
    // would make a replayed trace overwrite the file it came from.
    if (NEVER_RESTORED.includes(key)) continue;
    if (RECORDED_ENV_PREFIXES.some((prefix) => key.startsWith(prefix))) out[key] = value;
  }
  return out;
}

function gitRev(): string {
  try {
    // stderr discarded, as `build.ts`'s `gitHeadFor` does: the HEAD we could not
    // read is 'unknown' below, and git's own error can name the checkout.
    return execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return 'unknown';
  }
}

/**
 * A corpus file's publishable id: exactly what `crc32.shortId` produces, and
 * therefore exactly what `fixtureCorpus.corpusFileId` produces.
 *
 * It is also the test that tells an id apart from a corpus-relative path, which
 * is sound in one direction and that is the direction used: `discoverCorpus`
 * only ever yields paths carrying an importable extension, so a real path can
 * never be five bare hex characters.
 */
const CORPUS_ID = /^[0-9a-f]{5}$/;

/**
 * A corpus file's RESOLUTION key: exactly what `fixtureCorpus.corpusPathHash`
 * produces, 16 hex characters of SHA-256 over the corpus-relative path.
 *
 * Same one-directional test as `CORPUS_ID`, and sound for the same reason: a
 * real corpus path carries an importable extension, so it can never be sixteen
 * bare hex characters.
 */
const CORPUS_HASH = /^[0-9a-f]{16}$/;

/** A corpus reference reduced to its id. Idempotent, by the rule above. */
function asCorpusId(reference: string): string {
  return CORPUS_ID.test(reference) ? reference : shortId(reference);
}

/**
 * A corpus reference reduced to its path hash. Idempotent, by the rule above.
 *
 * Duplicated from `fixtureCorpus.corpusPathHash` rather than imported for the
 * same reason `shortId` lives in `crc32.ts`: this module is the one that reads
 * untrusted input and it may not depend on the module that walks somebody's data
 * directory. `fixtureCorpus.test.ts` pins that the two agree.
 */
function asCorpusHash(reference: string): string {
  if (CORPUS_HASH.test(reference)) return reference;
  return createHash('sha256').update(reference, 'utf8').digest('hex').slice(0, 16);
}

/**
 * The point a corpus file's real name stops existing.
 *
 * A scenario holds BOTH halves - it drew the entry from the inventory, so it has
 * the id and the corpus-relative path it needs to materialize the file - and
 * `importDialogFuzz` hands over the id. This fold is what makes that a property
 * of the recorder rather than of one caller remembering: hand it either, and a
 * recorded step carries the id.
 *
 * Folding HERE rather than in `writeTrace` means `snapshot()`, `build()` and
 * every shrink candidate carry the id too, so there is no window in which an
 * in-memory step and a written step disagree about what a trace may say. And it
 * is a fold rather than a throw because the caller is mid-run, usually holding a
 * failure worth keeping.
 */
function redactStep(step: TraceStep): TraceStep {
  if (step.kind !== 'corpusFile') return step;
  const corpusId = asCorpusId(step.corpusId);
  // The hash is derivable from a reference that is still a PATH, and not from
  // one already folded to an id - 20 bits does not come back. A caller holding
  // the entry passes both; a caller holding only the id gets a step without a
  // hash, which replays by the id and is refused if that id is ambiguous.
  const corpusHash =
    step.corpusHash !== undefined
      ? asCorpusHash(step.corpusHash)
      : CORPUS_ID.test(step.corpusId)
        ? undefined
        : asCorpusHash(step.corpusId);
  return corpusHash === undefined ? { ...step, corpusId } : { ...step, corpusId, corpusHash };
}

/**
 * The last segment of a `rel` that opens a CORPUS entry: the entry is named by
 * the directory its `corpusFile` step materialized into plus this token, never
 * by its file name.
 *
 * A corpus copy keeps its real basename on disk, because a `.mak` names its
 * sibling `.dat` files and a `.wpj` its `.srv` tree and renaming would break the
 * very files the corpus exists to exercise. The `corpusFile` step already
 * carried only the id; the `route` / `fileDialog` step that OPENED the copy
 * carried `<dir>/<real basename>`, so every corpus trace named its files anyway
 * - 14 and 17 distinct private names in two traces of one campaign, one of them
 * still in a 9-step shrink and printed in fuzz-shrink's action list (#576
 * HFI-13). A replayer resolves the token against the copy its own `corpusFile`
 * step just made; a token with no such step resolves to nothing and the move is
 * skipped and counted, exactly like an entry this machine does not have.
 */
export const CORPUS_ENTRY_SEGMENT = '@corpus-entry';

/** The `rel` that opens the entry materialized into `dirRel`. */
export function corpusEntryRel(dirRel: string): string {
  return `${dirRel}/${CORPUS_ENTRY_SEGMENT}`;
}

/** Is `rel` a corpus entry reference rather than a path on disk? */
export function isCorpusEntryRel(rel: string): boolean {
  return rel.split(/[/\\]/).pop() === CORPUS_ENTRY_SEGMENT;
}

/** Every session-relative path a step hands to the app or writes to. */
function stepRels(step: TraceStep): string[] {
  switch (step.kind) {
    case 'fileDialog':
      return step.rel === null ? [] : Array.isArray(step.rel) ? step.rel : [step.rel];
    case 'route':
    case 'genFile':
    case 'export':
      return [step.rel];
    case 'mutate':
      return FILE_ARG_ACTIONS.has(step.action) && typeof step.args[0] === 'string' ? [step.args[0]] : [];
    default:
      return [];
  }
}

/**
 * The index of the first step that names a file INSIDE a corpus copy by
 * anything other than `CORPUS_ENTRY_SEGMENT`, or -1 when none does.
 *
 * A trace-level rule rather than a per-step one, because a `rel` is only a
 * corpus name by virtue of sitting under a directory some `corpusFile` step
 * materialized into.
 */
export function corpusNameLeakAt(steps: readonly TraceStep[]): number {
  const slash = (rel: string): string => rel.split('\\').join('/').replace(/\/+$/, '');
  const dirs = steps.flatMap((step) => (step.kind === 'corpusFile' ? [`${slash(step.rel)}/`] : []));
  if (dirs.length === 0) return -1;
  return steps.findIndex((step) =>
    stepRels(step).some((rel) => {
      const target = slash(rel);
      return dirs.some((dir) => target.startsWith(dir) && target !== `${dir}${CORPUS_ENTRY_SEGMENT}`);
    }),
  );
}

/**
 * Collects the resolved move list for one run (or, for a per-cycle scenario, one
 * cycle). Observe-only: it never draws, never reads app state and never decides
 * anything.
 */
export class TraceRecorder {
  private steps: TraceStep[] = [];

  record(step: TraceStep): void {
    this.steps.push(redactStep(step));
  }

  /** Drop everything recorded so far. Used by scenarios whose iterations are independent. */
  reset(): void {
    this.steps = [];
  }

  get length(): number {
    return this.steps.length;
  }

  snapshot(): TraceStep[] {
    return this.steps.map((step) => ({ ...step }));
  }

  build(meta: {
    scenario: string;
    seed: number;
    iterations: number;
    fixture: string;
    stream: string;
    failure: { message: string } | null;
    /** Episode indices that ran with no project open; omitted when none did. */
    noProjectEpisodes?: readonly number[] | undefined;
  }): FuzzTrace {
    return {
      v: TRACE_VERSION,
      scenario: meta.scenario,
      seed: meta.seed,
      iterations: meta.iterations,
      fixture: meta.fixture,
      stream: meta.stream,
      env: recordedEnv(),
      gitRev: gitRev(),
      recordedAt: new Date().toISOString(),
      failure: meta.failure
        ? { message: meta.failure.message, signature: failureSignature(meta.failure.message) }
        : null,
      // Omitted rather than written empty: absent and "none of them" mean the
      // same thing on replay, and an always-present empty array would make every
      // trace look like it carried the field when older ones cannot.
      ...(meta.noProjectEpisodes && meta.noProjectEpisodes.length > 0
        ? { noProjectEpisodes: [...meta.noProjectEpisodes] }
        : {}),
      steps: this.snapshot(),
    };
  }
}

/**
 * Write a trace, refusing outright to emit one that names a corpus file.
 *
 * `TraceRecorder.record` already folded every corpus step to its id, so this
 * fires only for a trace assembled some other way - a shrink candidate built
 * from steps a future caller synthesised, or a hand-edited file being rewritten.
 * That is the case worth a hard failure rather than a silent fold: the write is
 * what makes the name durable and attachable, and a fold here would quietly
 * bless a code path that believed it could carry the path around.
 *
 * The refusal deliberately does not quote the offending value - an exception
 * message ends up in a log, which is the surface this whole rule protects.
 */
export function writeTrace(filePath: string, trace: FuzzTrace): string {
  trace.steps.forEach((step, index) => {
    if (step.kind !== 'corpusFile') return;
    if (!CORPUS_ID.test(step.corpusId)) {
      throw new Error(
        `refusing to write ${foldLocalPaths(filePath)}: step ${index + 1} names a corpus file by something ` +
          `other than its id, and a trace is an artifact people attach to bug reports`,
      );
    }
    // The hash field is a hash or it is absent. It is not rendered anywhere, so
    // a path parked in it would be the quietest leak available - which is
    // exactly why it is refused at the same door as the id.
    if (step.corpusHash !== undefined && !CORPUS_HASH.test(step.corpusHash)) {
      throw new Error(
        `refusing to write ${foldLocalPaths(filePath)}: step ${index + 1} carries a corpusHash that is not a ` +
          `path hash (16 hex characters), and a trace is an artifact people attach to bug reports`,
      );
    }
  });
  const leak = corpusNameLeakAt(trace.steps);
  if (leak >= 0) {
    throw new Error(
      `refusing to write ${foldLocalPaths(filePath)}: step ${leak + 1} opens a file inside a corpus copy by its name ` +
        `rather than as <dir>/${CORPUS_ENTRY_SEGMENT}, and a trace is an artifact people attach to bug reports`,
    );
  }
  // A trace is attached to issues, so its failure is the shareable form -
  // codes, counts and code locations - with the signature OF that form; the
  // full text is in the session's actions.jsonl (#576 W21-NF1).
  const failure =
    trace.failure === null
      ? null
      : { message: shareableFailureText(trace.failure.message), signature: shareableSignature(trace.failure.message) };
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, `${JSON.stringify({ ...trace, failure }, null, 2)}\n`, 'utf8');
  return filePath;
}

/** Every `kind` a step may carry. Anything else is not a step this build runs. */
const STEP_KINDS = new Set([
  'episode',
  'flow',
  'mutate',
  'undo',
  'redo',
  'undoTo',
  'redoTo',
  'save',
  'repair',
  'ui',
  'input',
  'fileDialog',
  'genFile',
  'corpusFile',
  'route',
  'mapClick',
  'export',
  'reload',
  'oracle',
]);

const INPUT_MODES = new Set(['type', 'select', 'check']);

/** A field that must be a non-empty string. */
function requireText(value: unknown, field: string, where: string): string {
  if (typeof value !== 'string' || value === '') {
    throw new Error(`${where} has ${field} ${valueShape(value)}; must be a non-empty string`);
  }
  return value;
}

/**
 * Every `rel` in a v2 step must stay INSIDE the session directory the replayer
 * chose. Absolute paths and `..` traversal are rejected outright.
 *
 * Same argument as `NEVER_RESTORED` above, applied to paths instead of to the
 * environment: a trace is a file, and a file arrives from wherever the reader
 * got it - the docs tell people to attach one to a bug report and shrink it.
 * These fields are joined against a session directory and then WRITTEN to
 * (`genFile`, `corpusFile`, `export`) or handed to the app to open. Honouring
 * `/etc/cron.d/x` or `../../../.ssh/authorized_keys` would let the file choose
 * what a replay creates, overwrites, or opens - the same "the file decides where
 * this process writes" hole the trace-path env knob is refused for.
 *
 * Windows spellings are checked explicitly: `path.isAbsolute` on Linux does not
 * consider `C:\x` or `\\server\share` absolute, and a trace is portable.
 */
function requireSessionRelative(value: unknown, field: string, where: string): void {
  const text = requireText(value, field, where);
  if (
    path.isAbsolute(text) ||
    text.startsWith('/') ||
    text.startsWith('\\') ||
    /^[A-Za-z]:/.test(text)
  ) {
    throw new Error(`${where} has an absolute ${field} ${valueShape(text)}; must be session-relative`);
  }
  if (text.split(/[/\\]/).some((segment) => segment === '..')) {
    throw new Error(`${where} has ${field} ${valueShape(text)} escaping the session directory`);
  }
}

/**
 * A corpus reference a trace is allowed to carry: the publishable id, and
 * nothing that could be a name.
 *
 * The message does not quote the value. A trace whose corpus step carries a real
 * path is precisely a leaked survey name, and `readTrace`'s exceptions are
 * printed by `scenario-run.ts` and `fuzz-shrink.ts`.
 */
function requireCorpusId(value: unknown, field: string, where: string): void {
  const text = requireText(value, field, where);
  if (!CORPUS_ID.test(text)) {
    throw new Error(
      `${where} has a ${field} that is not a corpus id (5 hex characters). A trace names a ` +
        `corpus file by its id, never by its path; re-record it on this build.`,
    );
  }
}

/**
 * The optional v4 resolution key. Absent is legal; anything that is not a path
 * hash is not.
 *
 * Same non-quoting rule as `requireCorpusId`, and the same reason: the value a
 * hand-written file could park here is a survey path, and this exception is
 * printed by `scenario-run.ts` and `fuzz-shrink.ts`. It also does the
 * session-relative check's job as a side effect - a hash has no separators.
 */
function requireCorpusHash(value: unknown, field: string, where: string): void {
  if (value === undefined) return;
  const text = requireText(value, field, where);
  if (!CORPUS_HASH.test(text)) {
    throw new Error(
      `${where} has a ${field} that is not a corpus path hash (16 hex characters). A trace ` +
        `resolves a corpus file by that hash, never by its path; re-record it on this build.`,
    );
  }
}

/**
 * Validate one step's SHAPE.
 *
 * The file is the untrusted input, and these fields reach control flow: `kind`
 * selects the branch (an unrecognised one used to fall through to the
 * history-move arm and replay as a redo), `steps` is clamped with `Math.min`
 * against the reach - which does not bound it from BELOW, so a negative moved
 * the model cursor the wrong way - `args` is spread into a store action, and
 * every v2 `rel` becomes a path the replayer writes to or opens.
 */
function validateStep(step: unknown, index: number, filePath: string): void {
  const where = `trace ${foldLocalPaths(filePath)} step ${index + 1}`;
  if (typeof step !== 'object' || step === null) throw new Error(`${where} is not an object`);
  const candidate = step as Partial<TraceStep> & Record<string, unknown>;
  if (typeof candidate.kind !== 'string' || !STEP_KINDS.has(candidate.kind)) {
    throw new Error(`${where} has kind ${valueShape(candidate.kind)}, which this build does not run`);
  }
  if (candidate.kind === 'mutate') {
    if (typeof candidate.action !== 'string') {
      throw new Error(`${where} is a mutation with no action name`);
    }
    if (!Array.isArray(candidate.args)) throw new Error(`${where} has args that are not an array`);
    // An action that takes a PATH is the one `mutate` shape whose arguments
    // reach the filesystem instead of the model - see `FILE_ARG_ACTIONS`.
    if (FILE_ARG_ACTIONS.has(candidate.action)) {
      requireSessionRelative(candidate.args[0], 'args[0]', `${where} (${candidate.action})`);
    }
  }
  if (candidate.kind === 'undoTo' || candidate.kind === 'redoTo') {
    const steps = candidate.steps;
    if (typeof steps !== 'number' || !Number.isSafeInteger(steps) || steps < 1) {
      throw new Error(`${where} jumps ${valueShape(steps)} step(s); must be a positive integer`);
    }
  }
  if (candidate.kind === 'ui') {
    requireText(candidate.testid, 'testid', where);
    requireText(candidate.label, 'label', where);
    if (candidate.double !== undefined && typeof candidate.double !== 'boolean') {
      throw new Error(`${where} has double ${valueShape(candidate.double)}; must be a boolean`);
    }
  }
  if (candidate.kind === 'input') {
    requireText(candidate.testid, 'testid', where);
    requireText(candidate.label, 'label', where);
    if (typeof candidate.value !== 'string') {
      throw new Error(`${where} has value ${valueShape(candidate.value)}; must be a string`);
    }
    if (typeof candidate.mode !== 'string' || !INPUT_MODES.has(candidate.mode)) {
      throw new Error(`${where} has input mode ${valueShape(candidate.mode)}, which this build does not run`);
    }
  }
  if (candidate.kind === 'fileDialog') {
    requireText(candidate.trigger, 'trigger', where);
    requireText(candidate.label, 'label', where);
    if (candidate.dialog !== 'open' && candidate.dialog !== 'save') {
      throw new Error(`${where} has dialog ${valueShape(candidate.dialog)}; must be 'open' or 'save'`);
    }
    const rel = candidate.rel;
    if (rel !== null) {
      // A cancel is `null`; anything else is one or more paths that get joined
      // against the session directory and answered into a native dialog.
      const paths = Array.isArray(rel) ? rel : [rel];
      if (paths.length === 0) throw new Error(`${where} answers the dialog with an empty path list`);
      paths.forEach((entry, at) => requireSessionRelative(entry, `rel[${at}]`, where));
    }
  }
  if (candidate.kind === 'episode') {
    requireText(candidate.label, 'label', where);
    if (typeof candidate.index !== 'number' || !Number.isInteger(candidate.index) || candidate.index < 0) {
      throw new Error(`${where}: episode index must be a non-negative integer`);
    }
    if (typeof candidate.headless !== 'boolean') {
      throw new Error(`${where}: episode headless must be a boolean`);
    }
  }
  if (candidate.kind === 'flow') {
    requireText(candidate.label, 'label', where);
    if (typeof candidate.index !== 'number' || !Number.isInteger(candidate.index) || candidate.index < 0) {
      throw new Error(`${where}: flow index must be a non-negative integer`);
    }
  }
  if (candidate.kind === 'genFile') {
    requireSessionRelative(candidate.rel, 'rel', where);
    requireText(candidate.label, 'label', where);
    if (typeof candidate.spec !== 'object' || candidate.spec === null) {
      throw new Error(`${where} has no generator spec to rebuild its file from`);
    }
  }
  if (candidate.kind === 'corpusFile') {
    // Not a path check but an IDENTITY check, and it does the path check's job
    // as a side effect: an id has no separators, so it can name neither an
    // absolute path nor a traversal out of the replayer's corpus root. What it
    // is really for is the v3 rule - a trace that names a corpus file is
    // refused at the door, whoever wrote it. `rel` is a genuine path, joined
    // against the replayer's session dir, and is checked as one.
    requireCorpusId(candidate.corpusId, 'corpusId', where);
    requireCorpusHash(candidate.corpusHash, 'corpusHash', where);
    requireSessionRelative(candidate.rel, 'rel', where);
    requireText(candidate.label, 'label', where);
  }
  if (candidate.kind === 'route') {
    requireSessionRelative(candidate.rel, 'rel', where);
    requireText(candidate.label, 'label', where);
  }
  if (candidate.kind === 'mapClick') {
    const at = candidate.lngLat;
    if (!Array.isArray(at) || at.length !== 2 || !at.every((value) => typeof value === 'number' && Number.isFinite(value))) {
      throw new Error(`${where} has lngLat ${valueShape(at)}; must be two finite numbers`);
    }
    requireText(candidate.label, 'label', where);
  }
  if (candidate.kind === 'export') {
    requireText(candidate.format, 'format', where);
    requireSessionRelative(candidate.rel, 'rel', where);
    requireText(candidate.label, 'label', where);
    if (typeof candidate.options !== 'object' || candidate.options === null) {
      throw new Error(`${where} has export options ${valueShape(candidate.options)}; must be an object`);
    }
  }
  if (candidate.kind === 'oracle') {
    // The NAME reaches control flow (the scenario dispatches on it) and `inputs`
    // is spread into an oracle's arguments, so both are shape-checked here and
    // the name is allowlisted by the scenario - the same two-layer rule as
    // `mutate`'s action.
    requireText(candidate.oracle, 'oracle', where);
    requireText(candidate.label, 'label', where);
    if (typeof candidate.inputs !== 'object' || candidate.inputs === null) {
      throw new Error(`${where} has oracle inputs ${valueShape(candidate.inputs)}; must be an object`);
    }
  }
  if (candidate.kind === 'reload') {
    const fixture = requireText(candidate.fixture, 'fixture', where);
    // A tracked fixture is named, never pathed. `materializeFixture` already
    // takes the basename, so this is belt and braces - but it is the difference
    // between a rule and a coincidence of another module's implementation.
    if (/[/\\]/.test(fixture) || fixture === '..') {
      throw new Error(`${where} names fixture ${valueShape(fixture)}; must be a bare fixture name`);
    }
  }
}

export function readTrace(filePath: string): FuzzTrace {
  const parsed = JSON.parse(fs.readFileSync(filePath, 'utf8')) as FuzzTrace;
  if (parsed.v !== TRACE_VERSION) {
    throw new Error(`trace ${foldLocalPaths(filePath)} is schema v${valueShape(parsed.v)}; this build reads v${TRACE_VERSION}`);
  }
  if (!Array.isArray(parsed.steps)) throw new Error(`trace ${foldLocalPaths(filePath)} has no steps array`);
  parsed.steps.forEach((step, index) => validateStep(step, index, filePath));
  // Same non-quoting rule as `requireCorpusId`: the value is a survey's name.
  const leak = corpusNameLeakAt(parsed.steps);
  if (leak >= 0) {
    throw new Error(
      `trace ${foldLocalPaths(filePath)} step ${leak + 1} opens a file inside a corpus copy by its name. A trace names ` +
        `a corpus entry as <dir>/${CORPUS_ENTRY_SEGMENT}, never by its file name; re-record it on this build.`,
    );
  }
  return parsed;
}

/** Where a run drops its trace when it fails. */
export function defaultTracePath(artifactsDir: string, scenario: string, seed: number): string {
  const stamp = new Date().toISOString().replace(/[:.]/g, '-');
  return path.join(artifactsDir, 'traces', `${scenario}-seed${seed}-${stamp}.json`);
}

/**
 * Everything in a failure message that must survive a shrink, and nothing that
 * must not.
 *
 * Digits are normalized out of the headline and the error line, and array
 * indices out of the path, for one reason: removing a mutation MOVES things. The
 * depth a failure happens at, the iteration number, the section index in a diff
 * path - all of them shift when an earlier action goes away, while the defect is
 * the same defect. A signature that pinned them would reject every genuine
 * reduction and the shrinker would never make progress.
 *
 * What is NOT normalized is the shape of the sentence, the field at the end of
 * the diff path, and every classifier id the message named. Those are what say
 * WHICH bug it is, so a shrink that lands on a different defect - which smaller
 * traces genuinely do - fails the comparison and is rejected, exactly as ddmin
 * requires.
 */
export function failureSignature(message: string): FailureSignature {
  const lines = message.split('\n');
  const headline = normalizeNumbers(lines[0] ?? '');

  let firstPath: string | null = null;
  let error: string | null = null;
  const classifiers = new Set<string>();
  for (const line of lines) {
    const pathMatch = /^\s+at (\S+)$/.exec(line);
    if (pathMatch && firstPath === null) firstPath = normalizeIndices(pathMatch[1] ?? '');
    const errorMatch = /^\s+error: (.+)$/.exec(line);
    if (errorMatch && error === null) error = normalizeNumbers(errorMatch[1] ?? '');
    for (const found of line.matchAll(/(?:KNOWN OPEN APP BUG|ATTRIBUTED) \[([a-z0-9-]+)\]/g)) {
      const id = found[1];
      if (id !== undefined) classifiers.add(id);
    }
    // An absolute-invariant breach has no diff path; its text is the identity.
    const invariant = /^\s+INVARIANT: (.+)$/.exec(line);
    if (invariant && firstPath === null) firstPath = `INVARIANT:${normalizeNumbers(invariant[1] ?? '')}`;
  }

  return { headline, path: firstPath, error, classifiers: [...classifiers].sort() };
}

/**
 * The signature a SHAREABLE artifact carries - a written trace, `fuzz-shrink`'s
 * output: `failureSignature` over `shareableFailureText`, so it names only what
 * that text keeps (headline, diff path, classifiers) and is the same for the
 * full message and for its shareable form. A shrink still compares the FULL
 * signature in memory.
 */
export function shareableSignature(message: string): FailureSignature {
  return failureSignature(shareableFailureText(message));
}

function normalizeNumbers(text: string): string {
  return text.replace(/\d+(\.\d+)?/g, 'N');
}

function normalizeIndices(text: string): string {
  return text.replace(/\[\d+\]/g, '[*]').replace(/\.\d+(\b|$)/g, '.N');
}

/** Do two failures name the same defect? */
export function sameSignature(a: FailureSignature, b: FailureSignature): boolean {
  return (
    a.headline === b.headline &&
    a.path === b.path &&
    a.error === b.error &&
    a.classifiers.length === b.classifiers.length &&
    a.classifiers.every((id, index) => id === b.classifiers[index])
  );
}

export function describeSignature(signature: FailureSignature): string {
  return [
    `  headline:    ${signature.headline}`,
    `  path:        ${signature.path ?? '(none)'}`,
    `  error:       ${signature.error ?? '(none)'}`,
    `  classifiers: ${signature.classifiers.length > 0 ? signature.classifiers.join(', ') : '(none)'}`,
  ].join('\n');
}

/** One line per step, for a human reading a shrunk trace. */
export function describeSteps(steps: readonly TraceStep[]): string {
  return steps.map((step, index) => `${String(index + 1).padStart(3, ' ')}. ${describeStep(step)}`).join('\n');
}

/**
 * One step, as a line.
 *
 * The v2 kinds print their own `label` plus the ONE fact the label cannot carry
 * - which testid, which corpus id, which format - because a shrunk trace is read
 * top to bottom by somebody deciding what to try next. A corpus step prints the
 * publishable id, which since v3 is the only thing the step has: the rule
 * `fixtureCorpus.ts` states now holds for the trace FILE as well as for the text
 * rendered from it.
 */
function describeStep(step: TraceStep): string {
  switch (step.kind) {
    case 'mutate':
      return step.label;
    case 'undoTo':
    case 'redoTo':
      return `${step.kind}(${step.steps} step(s))`;
    case 'ui':
      return `${step.double === true ? 'dblclick' : 'click'} ${step.testid} - ${step.label}`;
    case 'input':
      return `${step.mode} ${step.testid} - ${step.label}`;
    case 'fileDialog': {
      const answer =
        step.rel === null ? 'cancel' : Array.isArray(step.rel) ? `${step.rel.length} file(s)` : step.rel;
      return `${step.dialog}-dialog via ${step.trigger} -> ${answer} - ${step.label}`;
    }
    case 'episode':
      return `episode ${step.index}${step.headless ? ' (no project)' : ''}`;
    case 'flow':
      return `flow ${step.index}`;
    case 'genFile':
      return `genFile ${step.rel} - ${step.label}`;
    case 'corpusFile':
      // Printed, not folded: since v3 the step already holds the id, and folding
      // it again would print a tag that matched no metric key in the run beside
      // it. `asCorpusId` is what guarantees that, on both the record and the
      // read path.
      return `corpusFile #${step.corpusId} -> ${step.rel} - ${step.label}`;
    case 'route':
      return `route ${step.rel} - ${step.label}`;
    case 'mapClick':
      return `mapClick ${step.lngLat[0]},${step.lngLat[1]} - ${step.label}`;
    case 'export':
      return `export ${step.format} -> ${step.rel} - ${step.label}`;
    case 'oracle':
      return `oracle ${step.oracle} - ${step.label}`;
    case 'reload':
      return `reload ${step.fixture}`;
    default:
      return step.kind;
  }
}

