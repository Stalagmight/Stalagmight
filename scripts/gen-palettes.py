#!/usr/bin/env python3
"""Generate src/utils/palettes/catalog.generated.ts from matplotlib's colormaps.

The map's depth / distance colour scale offers matplotlib's named colormaps in
matplotlib's own groups (the "Choosing Colormaps" grouping). This script samples
each map and writes compact stop tables, so the app needs no runtime colormap
dependency.

Run it in a throwaway environment with the pinned matplotlib, never against the
repo's own Python modules (`-I` keeps the script directory off sys.path):

    pnpm gen:palettes
    # = uv run --no-project --python 3.12 --with matplotlib==3.10.7 python -I scripts/gen-palettes.py

Continuous maps are sampled at 256 points (matplotlib's own LUT size) and
simplified with Ramer-Douglas-Peucker until every dropped sample is within
TOLERANCE (0..255 units, per channel) of the linear interpolation between the
kept stops. Small ListedColormaps (the Qualitative group) are emitted as
discrete swatch lists, which the app draws as hard bands.

Licences for the derived data live in third_party/palettes/ (see its README).
"""

from __future__ import annotations

import pathlib
import sys

import matplotlib
from matplotlib.colors import ListedColormap

PINNED_VERSION = "3.10.7"
TOLERANCE = 1.0
OUT = pathlib.Path(__file__).resolve().parent.parent / "src/utils/palettes/catalog.generated.ts"

# matplotlib's "Choosing Colormaps" groups, in its order. Group ids are what
# the app keys its i18n group labels on (map.colorScale.groups.<id>).
GROUPS: list[tuple[str, list[str]]] = [
    ("mpl-perceptual", ["viridis", "plasma", "inferno", "magma", "cividis"]),
    (
        "mpl-sequential",
        [
            "Greys", "Purples", "Blues", "Greens", "Oranges", "Reds",
            "YlOrBr", "YlOrRd", "OrRd", "PuRd", "RdPu", "BuPu",
            "GnBu", "PuBu", "YlGnBu", "PuBuGn", "BuGn", "YlGn",
        ],
    ),
    (
        "mpl-sequential-2",
        [
            "binary", "gist_yarg", "gist_gray", "gray", "bone", "pink",
            "spring", "summer", "autumn", "winter", "cool", "Wistia",
            "hot", "afmhot", "gist_heat", "copper",
        ],
    ),
    (
        "mpl-diverging",
        [
            "PiYG", "PRGn", "BrBG", "PuOr", "RdGy", "RdBu", "RdYlBu",
            "RdYlGn", "Spectral", "coolwarm", "bwr", "seismic",
            "berlin", "managua", "vanimo",
        ],
    ),
    ("mpl-cyclic", ["twilight", "twilight_shifted", "hsv"]),
    (
        "mpl-qualitative",
        [
            "Pastel1", "Pastel2", "Paired", "Accent", "Dark2", "Set1",
            "Set2", "Set3", "tab10", "tab20", "tab20b", "tab20c",
        ],
    ),
    (
        "mpl-misc",
        [
            "flag", "prism", "ocean", "gist_earth", "terrain", "gist_stern",
            "gnuplot", "gnuplot2", "CMRmap", "cubehelix", "brg",
            "gist_rainbow", "rainbow", "jet", "turbo", "nipy_spectral",
            "gist_ncar",
        ],
    ),
]

SAMPLES = 256
DISCRETE_MAX = 20


def rdp(points: list[tuple[float, float, float, float]], lo: int, hi: int, keep: set[int]) -> None:
    """Keep the sample that deviates most from the lo..hi chord, recursively."""
    if hi - lo < 2:
        return
    t0, *c0 = points[lo]
    t1, *c1 = points[hi]
    worst = -1.0
    worst_i = -1
    for i in range(lo + 1, hi):
        t, *c = points[i]
        f = (t - t0) / (t1 - t0)
        err = max(abs(c[k] - (c0[k] + (c1[k] - c0[k]) * f)) for k in range(3))
        if err > worst:
            worst = err
            worst_i = i
    if worst > TOLERANCE:
        keep.add(worst_i)
        rdp(points, lo, worst_i, keep)
        rdp(points, worst_i, hi, keep)


def fmt_pos(t: float) -> str:
    s = f"{t:.4f}".rstrip("0").rstrip(".")
    return s or "0"


def continuous_stops(cmap) -> list[str]:
    points = []
    for i in range(SAMPLES):
        t = i / (SAMPLES - 1)
        r, g, b, _a = cmap(t)
        points.append((t, r * 255.0, g * 255.0, b * 255.0))
    keep = {0, SAMPLES - 1}
    rdp(points, 0, SAMPLES - 1, keep)
    out = []
    for i in sorted(keep):
        t, r, g, b = points[i]
        out.append(f"{fmt_pos(t)},{round(r)},{round(g)},{round(b)}")
    return out


def discrete_colors(cmap: ListedColormap) -> list[str]:
    out = []
    for color in cmap.colors:
        r, g, b = (float(color[k]) for k in range(3))
        out.append(f"{round(r * 255)},{round(g * 255)},{round(b * 255)}")
    return out


def main() -> int:
    if matplotlib.__version__ != PINNED_VERSION:
        print(
            f"matplotlib {matplotlib.__version__} found, {PINNED_VERSION} pinned; "
            "run via the uv command in this file's docstring",
            file=sys.stderr,
        )
        return 1
    seen: set[str] = set()
    lines = [
        "// GENERATED by scripts/gen-palettes.py from matplotlib "
        f"{PINNED_VERSION}. Do not edit by hand.",
        "// Licences for this derived colormap data: third_party/palettes/README.md.",
        "import type { GeneratedPalette } from './types';",
        "",
        "export const GENERATED_PALETTES: readonly GeneratedPalette[] = [",
    ]
    for group, names in GROUPS:
        for name in names:
            cmap = matplotlib.colormaps[name]
            pid = "mpl." + name.lower()
            if pid in seen:
                raise SystemExit(f"duplicate palette id {pid}")
            seen.add(pid)
            if isinstance(cmap, ListedColormap) and cmap.N <= DISCRETE_MAX:
                data = discrete_colors(cmap)
                lines.append(
                    f"  {{ id: '{pid}', name: '{name}', group: '{group}', kind: 'discrete', "
                    f"data: [{', '.join(data)}] }},"
                )
            else:
                data = continuous_stops(cmap)
                lines.append(
                    f"  {{ id: '{pid}', name: '{name}', group: '{group}', kind: 'stops', "
                    f"data: [{', '.join(data)}] }},"
                )
    lines.append("];")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(seen)} palettes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
