// Turn an agent session's action log into a runnable WebdriverIO replay spec.
//
// Reads .agent-artifacts/sessions/<id>/actions.jsonl (the JSONL contract in
// docs/agent-harness.md) and emits a mocha/wdio spec where every recorded
// action becomes real WebDriver code (using the `resolved` selectors/points the
// harness captured) or, for observation-only tools, a numbered comment. The
// spec therefore maps 1:1 to the recorded steps and reproduces the session.
//
// Interaction tools (click/type_text/press_keys/hover/drag/scroll/select_option/
// file_dialog_answer/eval/ipc/store_action/map_click/map_feature_click/seed/driver_script/
// run_scenario) and all semantic waits emit executable code;
// screenshot/store_state/logs/map_view/check_problems/app_* emit
// `// [seq N] <tool>` comments, and every os_* (Tier 2 trusted input) emits a
// `(OS-level; not replayable)` comment carrying its recorded params.
// Inter-action gaps over 250ms become bounded
// pauses. With --assert-final, the last store_state read becomes a hard expect
// against its recorded value (skipped, with a comment, if it was truncated).
//
// Usage:
//   node scripts/generate-replay.mjs <sessionDirOrJsonl> [--out <file>] [--name <n>] [--assert-final]
//   node scripts/generate-replay.mjs .agent-artifacts/sessions/20260703-...  --out e2e/agent/replays/repro.spec.ts
//
// With no --out, writes replay.spec.ts inside the session dir (uncommitted).
// No in-repo runner today (#549 retired the WDIO one; the #466 replay-runner
// phase replaces it) - the spec is the reviewable record of the steps.

import * as fs from 'fs';
import * as path from 'path';
import { foldLocalPaths } from './lib/fold-local-paths.mjs';
import { testIdSelector } from './lib/test-id-selector.mjs';

const args = process.argv.slice(2);
if (args.length === 0 || args[0].startsWith('--')) {
  process.stderr.write('usage: node scripts/generate-replay.mjs <sessionDirOrJsonl> [--out file] [--name n] [--assert-final]\n');
  process.exit(2);
}

const input = args[0];
const getFlag = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const assertFinal = args.includes('--assert-final');
const nameArg = getFlag('--name');

const jsonlPath = fs.existsSync(input) && fs.statSync(input).isDirectory()
  ? path.join(input, 'actions.jsonl')
  : input;
if (!fs.existsSync(jsonlPath)) {
  // Folded: it is the path the caller gave, which can name the user's own
  // directories (#576 W51, W58).
  process.stderr.write(`no actions.jsonl at ${foldLocalPaths(jsonlPath)}\n`);
  process.exit(1);
}

const sessionDir = path.dirname(jsonlPath);
const records = fs
  .readFileSync(jsonlPath, 'utf8')
  .split('\n')
  .filter((l) => l.trim().length > 0)
  .map((l) => {
    try {
      return JSON.parse(l);
    } catch {
      return null; // Tolerate a truncated final line.
    }
  })
  .filter(Boolean);

const start = records.find((r) => r.type === 'session-start');
const actions = records.filter((r) => r.type === 'action');
const specName = nameArg || (start?.sessionId ?? path.basename(sessionDir));
const outPath = getFlag('--out') || path.join(sessionDir, 'replay.spec.ts');

const q = (v) => JSON.stringify(v ?? null);
const lines = [];
const push = (s = '') => lines.push(s);

// Import specifier for replayHelpers, relative to wherever this spec lands
// (session dir when uncommitted, e2e/agent/replays/ when curated).
let helpersImport = path
  .relative(path.dirname(path.resolve(outPath)), path.resolve('e2e/agent/lib/replayHelpers'))
  .split(path.sep)
  .join('/');
if (!helpersImport.startsWith('.')) helpersImport = `./${helpersImport}`;

// Index of the last store_state action (for --assert-final).
const lastStateIdx = assertFinal
  ? actions.map((a, i) => (a.tool === 'store_state' ? i : -1)).reduce((acc, i) => (i >= 0 ? i : acc), -1)
  : -1;

push('// AUTO-GENERATED by scripts/generate-replay.mjs. Edit the source session, not this file.');
push(`// session: ${start?.sessionId ?? '(unknown)'}  gitHead: ${start?.gitHead ?? '?'}`);
push(`// binary:  ${start?.binaryPath ?? '?'}  display: ${start?.display ?? '?'}`);
push(`import { ipc, evalInApp, pause, storeAction, driverScript, runScenarioReplay, replayClick, mapClick, mapFeatureClick, waitForReplay, hoverElement, dragPointer, scrollTarget, selectOption, answerFileDialog, materializeReplayFixture, cleanupReplayFixtures } from '${helpersImport}';`);
push('');
push('// eslint-disable-next-line @typescript-eslint/no-explicit-any -- a runner global, untyped in a generated spec');
push('declare const browser: any;');
push('// eslint-disable-next-line @typescript-eslint/no-explicit-any -- a runner global, untyped in a generated spec');
push('declare const $: any;');
push('// eslint-disable-next-line @typescript-eslint/no-explicit-any -- a runner global, untyped in a generated spec');
push('declare const expect: any;');
push('');
push(`describe('replay ${specName}', () => {`);
push('  afterEach(() => cleanupReplayFixtures());');
push(`  it('reproduces the recorded session', async () => {`);

let prevTs = null;
for (let i = 0; i < actions.length; i++) {
  const a = actions[i];
  const p = a.params ?? {};
  const r = a.resolved ?? {};

  // Bounded pause for a real recorded gap.
  if (prevTs && a.ts) {
    const gap = Date.parse(a.ts) - Date.parse(prevTs);
    if (gap > 250) push(`    await pause(browser, ${Math.min(gap, 2000)});`);
  }
  prevTs = a.ts ?? prevTs;

  const outcome = a.outcome?.ok === false ? '  (recorded: FAILED)' : '';

  // Tier 2 OS-level tools (os_grant/os_click/os_keys/os_screenshot) are recorded
  // like any other action - they mutate app state and repro reports need them -
  // but they are never replayed: trusted input would need the TCC grants, a
  // frontmost desktop and pixel determinism, none of which are portable to
  // another machine or to CI. A load-bearing os_* step is hand-converted to a
  // Tier 1 equivalent; this comment preserves the intent and the arguments.
  // Matched by prefix so a future os_* tool needs no change here.
  if (typeof a.tool === 'string' && a.tool.startsWith('os_')) {
    push(`    // [seq ${a.seq}] ${a.tool}${outcome} ${compactParams(p)} (OS-level; not replayable)`);
    continue;
  }

  push(`    // [seq ${a.seq}] ${a.tool}${outcome}`);

  switch (a.tool) {
    case 'click': {
      const selector = p.testid ? testIdSelector(p.testid) : (r.selector ?? p.selector);
      const point = r.point ?? (typeof p.x === 'number' && typeof p.y === 'number' ? { x: p.x, y: p.y } : undefined);
      if (selector || point) {
        push(`    await replayClick(browser, ${q({ selector, ...point, button: p.button, double: p.double, modifiers: p.modifiers })});`);
      } else {
        push(`    // click had no resolved target; skipped`);
      }
      break;
    }
    case 'map_click': {
      if (Array.isArray(p.lngLat) && p.lngLat.length === 2) {
        push(`    await mapClick(browser, ${q(p.lngLat)}, ${q(p.button ?? 'left')});`);
      } else push(`    // map_click had no recorded lngLat; skipped`);
      break;
    }
    case 'map_feature_click': {
      if (p.featureType && Number.isInteger(p.sectionId)) {
        push(`    await mapFeatureClick(browser, ${q(p)});`);
      } else push(`    // map_feature_click had no recorded feature identity; skipped`);
      break;
    }
    case 'type_text': {
      const sel = p.testid ? testIdSelector(p.testid) : (r.selector ?? p.selector);
      if (sel) {
        if (p.clear) push(`    await $(${q(sel)}).clearValue();`);
        push(`    await $(${q(sel)}).setValue(${q(p.text ?? '')});`);
      } else {
        push(`    await browser.keys(${q(String(p.text ?? '').split(''))});`);
      }
      if (p.submit) push(`    await browser.keys(['Enter']);`);
      break;
    }
    case 'press_keys':
      push(`    await browser.keys(${q(p.keys ?? [])});`);
      break;
    case 'hover':
      push(`    await hoverElement(browser, ${q({ testid: p.testid, selector: p.testid ? undefined : (r.selector ?? p.selector) })});`);
      break;
    case 'drag':
      push(`    await dragPointer(browser, ${q(p)});`);
      break;
    case 'scroll':
      push(`    await scrollTarget(browser, ${q(p)});`);
      break;
    case 'select_option':
      push(`    await selectOption(browser, ${q(p)});`);
      break;
    case 'file_dialog_answer': {
      const value = p.cancel ? null : (p.paths ?? p.path ?? null);
      push(`    await answerFileDialog(browser, ${q(p.triggerTestid)}, ${q(p.kind)}, ${q(value)});`);
      break;
    }
    case 'eval':
      push(`    await evalInApp(browser, ${q(p.script ?? '')}, ${q(p.args ?? [])});`);
      break;
    case 'ipc':
      push(`    await ipc(browser, ${q(p.command ?? '')}, ${q(p.args ?? {})});`);
      break;
    case 'store_action':
      push(`    await storeAction(browser, ${q(p.store)}, ${q(p.action)}, ${q(p.args ?? [])});`);
      break;
    case 'seed': {
      if (p.mode === 'basic') {
        push(`    await storeAction(browser, 'project', 'createProject', ${q([p.projectName ?? 'harness-project'])});`);
      } else if (p.name || p.mode === 'fixture' || p.mode === 'fractal') {
        const fixture = p.name ?? 'fractal_plant_iter3.stalx';
        push(`    await storeAction(browser, 'project', 'loadProject', [materializeReplayFixture(${q(fixture)})]);`);
      } else {
        push(`    // seed had no resolved fixture path; skipped`);
      }
      break;
    }
    case 'driver_script': {
      if (a.outcome?.ok === false) {
        push(`    // driver_script recorded as FAILED; skipped to avoid replaying a timed-out background body`);
        break;
      }
      const dsCall = `driverScript(browser, ${q(p.script ?? '')}${p.timeoutMs != null ? `, ${p.timeoutMs}` : ''})`;
      push(`    await ${dsCall};`);
      break;
    }
    case 'run_scenario': {
      const scCall = `runScenarioReplay(browser, ${q(p.name)}, ${q(p.seed ?? 1)}, ${p.iterations != null ? p.iterations : 'undefined'})`;
      if (a.outcome?.ok === false) push(`    await ${scCall}.catch(() => undefined); // recorded as FAILED`);
      else push(`    await ${scCall};`);
      break;
    }
    case 'map_view':
      if (p.set) push(`    await evalInApp(browser, 'const m=window.__stalagmight_map__; if(m) m.jumpTo(args[0]); return true;', [${q(p.set)}]);`);
      else push(`    // [seq ${a.seq}] map_view (read-only)`);
      break;
    case 'wait_for': {
      push(`    await waitForReplay(browser, ${q(p)});`);
      break;
    }
    case 'store_state': {
      if (i === lastStateIdx && a.result && typeof a.result === 'object' && a.result.truncated) {
        push(`    // [seq ${a.seq}] store_state: recorded value was truncated; final-state assertion skipped`);
      } else if (i === lastStateIdx && a.result) {
        const dot = p.path ? `.${p.path}` : '';
        push(`    // final-state assertion (${p.store}${dot})`);
        push(`    const finalState = await evalInApp(browser, 'const s=window.__E2E_TEST__[${q(storeKey(p.store))}].getState(); ${p.path ? `let v=s; for (const k of ${q(String(p.path).split('.'))}) v = v==null?v:v[k]; return v;` : 'return Object.keys(s);'}');`);
        push(`    expect(finalState).toEqual(${q(a.result.value ?? a.result.keys ?? null)});`);
      } else {
        push(`    // [seq ${a.seq}] store_state ${p.store}${p.path ? `.${p.path}` : ''} (observation)`);
      }
      break;
    }
    default:
      // screenshot / logs / element_state / check_problems / app_*: observation.
      push(`    // [seq ${a.seq}] ${a.tool} (observation; not replayed)`);
  }
}

push('  });');
push('});');
push('');

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, lines.join('\n'));
// Folded: --out and the session dir are the caller's paths (#576 W51, W58).
process.stdout.write(`wrote ${foldLocalPaths(outPath)} (${actions.length} actions)\n`);
process.stdout.write('note: no in-repo runner yet - see e2e/agent/replays/README.md\n');

// Recorded params inlined into a one-line comment. JSON never contains a raw
// newline, so the comment cannot break out of its line; the cap keeps a long
// screenshot path or key spec from bloating the spec.
function compactParams(params) {
  const json = JSON.stringify(params ?? {});
  return json.length > 200 ? `${json.slice(0, 197)}...` : json;
}

function storeKey(store) {
  const map = {
    ui: 'uiStore',
    project: 'projectStore',
    globalView: 'globalViewStore',
    gasPlan: 'gasPlanStore',
    speleo: 'speleoStore',
    export: 'exportStore',
    network: 'networkStore',
  };
  return map[store] ?? store;
}
