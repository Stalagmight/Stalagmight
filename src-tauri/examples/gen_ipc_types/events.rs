//! The backend -> webview event manifest (#576 C13): every event declared in
//! `core::events`, by name, with its payload type, written as
//! `src/types/ipc/IpcEvents.ts` for the frontend's listeners (`listenIpc`).
//!
//! Nothing is parsed here: each entry is a type that implements `IpcEvent`, so
//! its name and payload come from the one Rust declaration the emitters use.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use stalagmight_lib::core::events::{
    CloseRequested, InternalErrorEvent, IpcEvent, LaunchFileQueued, LoadingProgressEvent,
    SpeleoPrePushSave, TileTransportError, TileTransportSuccess,
};
use ts_rs::TS;

struct Event {
    name: &'static str,
    payload: String,
}

fn event<E: IpcEvent>() -> Event {
    Event {
        name: E::NAME,
        payload: <E::Payload as TS>::name(),
    }
}

/// `loading-progress` -> `LOADING_PROGRESS`, `tauri://close-requested` -> `TAURI_CLOSE_REQUESTED`.
fn const_key(name: &str) -> String {
    name.split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|part| !part.is_empty())
        .map(str::to_ascii_uppercase)
        .collect::<Vec<_>>()
        .join("_")
}

/// Write `IpcEvents.ts`. `exported` is every generated TS type name, for imports.
pub(crate) fn write_events(out_dir: &Path, exported: &BTreeSet<String>) {
    let events = [
        event::<LoadingProgressEvent>(),
        event::<TileTransportSuccess>(),
        event::<TileTransportError>(),
        event::<LaunchFileQueued>(),
        event::<CloseRequested>(),
        event::<InternalErrorEvent>(),
        event::<SpeleoPrePushSave>(),
    ];
    let mut out = String::from(
        "// This file is generated by `pnpm gen:ipc-types` from the `IpcEvent` declarations in \
         core::events. Do not edit by hand.\n",
    );
    let imports: BTreeSet<&String> = events
        .iter()
        .map(|e| &e.payload)
        .filter(|payload| exported.contains(*payload))
        .collect();
    for name in imports {
        let _ = writeln!(out, "import type {{ {name} }} from \"./{name}\";");
    }
    out.push_str(
        "\n/** Every event the backend emits to the webview, by name, with its payload (#576 C13). */\n\
         export interface IpcEvents {\n",
    );
    for e in &events {
        let _ = writeln!(out, "  \"{}\": {};", e.name, e.payload);
    }
    out.push_str("}\n\n/** The event names, for `listenIpc(IPC_EVENTS.<NAME>, ...)`. */\nexport const IPC_EVENTS = {\n");
    for e in &events {
        let _ = writeln!(out, "  {}: \"{}\",", const_key(e.name), e.name);
    }
    out.push_str("} as const;\n");
    fs::write(out_dir.join("IpcEvents.ts"), out).expect("Failed to write IpcEvents.ts");
}
