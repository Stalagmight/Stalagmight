// ESLint gate with a per-file warning ratchet (#576 D1).
//
// The repo had no JS/TS linter, yet ~40 `eslint-disable` comments told one to
// look away - so the hook rules they named had never run. This gate runs ESLint
// (config: eslint.config.js) over LINT_TARGETS and enforces two things:
//
//   - every ERROR fails: react-hooks/rules-of-hooks (a hook behind `||`, an
//     early return or a condition changes the hook order between renders and
//     crashes the component), an unused or unknown-rule `eslint-disable`
//     directive (linterOptions.reportUnusedDisableDirectives), a parse error;
//   - every WARNING is ratcheted: the count per file and per rule may not grow
//     past eslint-baseline.json, and a file or rule that is not recorded may not
//     warn at all. react-hooks/exhaustive-deps is warn-level because the tree
//     already carried ~100 findings when the linter landed; fixing them is
//     separate work, so they are frozen here instead of being waved through.
//
// The ratchet is strict in both directions: a count BELOW its baseline also
// fails, with "run --update to lock it in". Otherwise a fixed warning would leave
// slack that the next change could quietly spend, and "the count may only
// shrink" would not hold.
//
// Usage:  node scripts/check-eslint.mjs            (pnpm lint:eslint)
//         node scripts/check-eslint.mjs --update   (rewrite the baseline from this tree)
//
// The fixture test (scripts/check-eslint.test.mjs, pnpm lint:eslint:test) pins
// the ratchet arithmetic and that the real config still reports each rule.

import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';
import { ESLint } from 'eslint';

export const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const BASELINE_FILE = 'eslint-baseline.json';
// What the gate lints. The globs in eslint.config.js decide which files under
// these directories get which rules.
export const LINT_TARGETS = ['src', 'e2e-playwright', 'e2e'];

const relPosix = (abs) => path.relative(REPO_ROOT, abs).split(path.sep).join('/');

// ESLint results -> {errors: [{file, line, column, ruleId, message}], warnings:
// {rule: {file: count}}}. A fatal message (parse error) counts as an error.
export function summarize(results, rel = relPosix) {
  const errors = [];
  const warnings = {};
  for (const r of results) {
    const file = rel(r.filePath);
    for (const m of r.messages) {
      const ruleId = m.ruleId ?? '(no rule)';
      if (m.fatal || m.severity === 2) {
        errors.push({ file, line: m.line ?? 0, column: m.column ?? 0, ruleId, message: m.message });
      } else if (m.severity === 1) {
        warnings[ruleId] ??= {};
        warnings[ruleId][file] = (warnings[ruleId][file] ?? 0) + 1;
      }
    }
  }
  return { errors, warnings };
}

// Compare measured warning counts with the recorded ones. Returns {grown,
// loosened}: `grown` are new or increased counts (always a failure), `loosened`
// are counts below the baseline (also a failure until --update locks them in).
export function ratchet(measured, recorded) {
  const grown = [];
  const loosened = [];
  const rules = new Set([...Object.keys(measured), ...Object.keys(recorded)]);
  for (const rule of [...rules].sort()) {
    const m = measured[rule] ?? {};
    const r = recorded[rule] ?? {};
    const files = new Set([...Object.keys(m), ...Object.keys(r)]);
    for (const file of [...files].sort()) {
      const have = m[file] ?? 0;
      const allowed = r[file] ?? 0;
      if (have > allowed) grown.push({ rule, file, have, allowed });
      else if (have < allowed) loosened.push({ rule, file, have, allowed });
    }
  }
  return { grown, loosened };
}

export const total = (counts) =>
  Object.values(counts).reduce((sum, perFile) => sum + Object.values(perFile).reduce((a, b) => a + b, 0), 0);

function sortCounts(counts) {
  const out = {};
  for (const rule of Object.keys(counts).sort()) {
    out[rule] = {};
    for (const file of Object.keys(counts[rule]).sort()) out[rule][file] = counts[rule][file];
  }
  return out;
}

export function baselinePayload(warnings) {
  return {
    _README:
      'Generated by scripts/check-eslint.mjs --update. ESLint warning counts per rule and ' +
      'per file over the gate scope (LINT_TARGETS in the script; rules in eslint.config.js). ' +
      'The CI gate fails when a count grows, when an unrecorded file or rule warns, and when ' +
      'a count drops below its row (run --update to lock the improvement in). Errors are never ' +
      'recorded here: they always fail. Raising a number is a review-visible decision - fix the ' +
      'warning instead unless there is a reason.',
    total: total(warnings),
    warnings: sortCounts(warnings),
  };
}

function loadBaseline(file) {
  if (!fs.existsSync(file)) return { warnings: {} };
  try {
    const parsed = JSON.parse(fs.readFileSync(file, 'utf8'));
    return { warnings: parsed.warnings ?? {} };
  } catch (e) {
    console.error(`check-eslint: ${BASELINE_FILE} is not valid JSON (${e.code || e.message}). Regenerate it with: pnpm lint:eslint --update`);
    process.exit(1);
  }
}

function printErrors(errors) {
  for (const e of errors) console.error(`  ${e.file}:${e.line}:${e.column}  ${e.ruleId}  ${e.message.split('\n')[0]}`);
}

export async function main(argv = process.argv.slice(2)) {
  const eslint = new ESLint({ cwd: REPO_ROOT });
  const results = await eslint.lintFiles(LINT_TARGETS);
  const { errors, warnings } = summarize(results);
  const baselinePath = path.join(REPO_ROOT, BASELINE_FILE);

  if (argv.includes('--update')) {
    if (errors.length > 0) {
      console.error(`\n✗ ESLint: ${errors.length} error(s) - errors are never baselined, fix them first:\n`);
      printErrors(errors);
      return 1;
    }
    fs.writeFileSync(baselinePath, JSON.stringify(baselinePayload(warnings), null, 2) + '\n');
    console.log(`baseline updated: ${total(warnings)} warning(s) recorded in ${BASELINE_FILE}.`);
    return 0;
  }

  const recorded = loadBaseline(baselinePath).warnings;
  const { grown, loosened } = ratchet(warnings, recorded);
  let failed = false;
  if (errors.length > 0) {
    failed = true;
    console.error(`\n✗ ESLint: ${errors.length} error(s):\n`);
    printErrors(errors);
  }
  if (grown.length > 0) {
    failed = true;
    console.error(`\n✗ ESLint warning ratchet: ${grown.length} file(s) warn more than ${BASELINE_FILE} allows:\n`);
    for (const g of grown) console.error(`  ${g.file}  ${g.rule}: ${g.have} (baseline ${g.allowed})`);
    console.error(`\nFix the new warning(s) (run: pnpm exec eslint <file>), or justify the growth and run --update.`);
  }
  if (loosened.length > 0) {
    failed = true;
    console.error(`\n✗ ESLint warning ratchet: ${loosened.length} file(s) now warn LESS than recorded - lock it in:\n`);
    for (const l of loosened) console.error(`  ${l.file}  ${l.rule}: ${l.have} (baseline ${l.allowed})`);
    console.error(`\nRun: pnpm lint:eslint --update   and commit ${BASELINE_FILE}.`);
  }
  if (failed) return 1;
  console.log(
    `✓ ESLint: ${results.length} files in ${LINT_TARGETS.join(', ')}, no errors, ` +
      `${total(warnings)} warning(s), all within ${BASELINE_FILE}.`,
  );
  return 0;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) process.exit(await main());
